medida as (
  select l.id,
    case when r.i1 = r.i0 then 0::numeric
         else (coalesce(l.bay, split_part(l.code, '-', 3)::int) - r.i0)::numeric / (r.i1 - r.i0)
    end as t,
    r.*
  from location l
  join lane la on la.id = l.lane_id
  join recta r on r.carril = la.code and r.fondo = coalesce(l.depth_index, 1)
  where l.retired_at is null and l.kind <> 'staging'
)
update location l
set coord_x = round(m.x0 + m.t * (m.x1 - m.x0), 2),
    coord_y = round(m.y0 + m.t * (m.y1 - m.y0), 2),
    dist_despacho_m = round(m.d0 + m.t * (m.d1 - m.d0), 2)
from medida m
where m.id = l.id;

-- El recorrido: los carriles por lo cerca que estan de despacho, y cada uno desde la boca.
with boca as (
  select l.lane_id, min(l.dist_despacho_m) as cerca
  from location l
  where l.retired_at is null and l.kind <> 'staging' and l.dist_despacho_m is not null
  group by l.lane_id
),
orden as (
  select l.id,
    row_number() over (
      order by b.cerca, la.code, l.dist_despacho_m,
               coalesce(l.level, 0), coalesce(l.depth_index, 1), l.code
    )::integer as n
  from location l
  join lane la on la.id = l.lane_id
  join boca b on b.lane_id = l.lane_id
  where l.retired_at is null and l.kind <> 'staging' and l.dist_despacho_m is not null
)
update location l set pick_sequence = o.n from orden o where o.id = l.id;

