-- El plano trae las medidas
--
-- Hasta hoy el WMS sabia donde estaba cada posicion solo por su codigo: `coord_x`, `coord_y`,
-- `pick_sequence` y `max_weight_kg` estaban en nulo en las 5,605 posiciones. Y `pick_sequence`
-- es la que ordena la colocacion, el recorrido del surtido, el reabastecimiento y los conteos:
-- con todas en nulo el orden que salia era el alfabetico del codigo. La migracion 0057 ya lo
-- decia.
--
-- El maestro de ubicaciones del 12/11/2026 (planos P4-A2 y P4-A5) trae X, Y y la distancia a
-- despacho de las 5,581 posiciones de almacenaje. Se comprobo posicion por posicion contra las
-- nuestras: **las 5,581 emparejan una a una, ninguna sobra y ninguna falta**. Sus codigos
-- `CMY-...` no se usan; los nuestros se quedan.
--
-- Las medidas no van una por una porque no hacen falta: dentro de un carril X e Y son una
-- recta. Van los dos extremos de cada carril y lo de en medio se interpola. Son 238 rectas
-- —200 carriles de piso y 19 de rack por sus dos fondos— y salen las 5,581 posiciones con un
-- error de menos de 5 cm, que es el redondeo del propio archivo.
--
-- `pick_sequence` sale de ahi, y es un recorrido, no un orden alfabetico: los carriles por su
-- distancia a despacho, y cada carril desde la boca hacia el fondo, niveles de abajo arriba.
-- No es la serpentina del surtido por ruta, que es otra cosa y esta pendiente.
--
-- El grupo permitido tambien viene del plano, y resulta ser dos bloques enteros: la zona F1
-- (Piso Norte-Oeste) y los cuatro primeros carriles del rack de abarroteria, 1,043 posiciones
-- para lo que no es alimento. El dato del producto ya existia —`product.contamination_class`,
-- 114 quimicos, 29 no alimentos y 11 aromaticos— y no lo usaba nadie. Aqui queda el otro lado.

